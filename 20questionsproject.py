def query_phi3(prompt, max_tokens=10, temperature=0.1):
    """
    Query phi-3 model using the loaded pipeline

    Args:
        prompt: The question/prompt to send to the model
        max_tokens: Maximum tokens to generate (keep low for yes/no answers)
        temperature: Sampling temperature (0.1 for consistency)

    Returns:
        Generated text response or None if error
    """
    try:
        # Generate response
        response = pipe(
            prompt,
            max_new_tokens=max_tokens,
            temperature=temperature,
            do_sample=temperature > 0,
            pad_token_id=tokenizer.eos_token_id
        )

        # Extract the generated text
        if response and len(response) > 0:
            generated_text = response[0]['generated_text'].strip()
            return generated_text
        else:
            return None

    except Exception as e:
        print(f"Error querying model: {e}")
        return None

