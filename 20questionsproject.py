def generate_noun_properties(noun, properties_list, verbose=True):
    """
    Generate all property values for a single noun using phi-3
    """
    noun_data = {'noun': noun}

    if verbose:
        print(f"\n{'='*60}")
        print(f"Processing: {noun}")
        print('='*60)

    for prop in properties_list:
        # Use the improved prompt function (v2)
        prompt, ptype = create_property_prompt_v2(noun, prop)

        if prompt and ptype:
            if verbose:
                print(f"\n  Property: {prop} ({ptype})")

            # Query the model
            response = query_phi3(prompt, max_tokens=15)  # Slightly more tokens for scale responses

            if response:
                parsed_value = parse_llm_response(response, ptype)
                noun_data[prop] = parsed_value

                if verbose:
                    print(f"  Response: {response}")
                    print(f"  Parsed: {parsed_value}")
            else:
                noun_data[prop] = None
                if verbose:
                    print(f"  ❌ No response")

    return noun_data

