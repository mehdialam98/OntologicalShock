def parse_llm_response(response, property_type):
    """
    Parse the LLM response into a usable value
    Enhanced to handle phi-3 response formats
    """
    if not response:
        return None

    response = response.lower().strip()

    if property_type == 'binary':
        # Remove common artifacts
        response = response.replace('.', '').replace(',', '').replace('!', '')

        # Direct yes/no detection
        if response == 'yes':
            return True
        elif response == 'no':
            return False

        # Check if yes appears without no
        if 'yes' in response and 'no' not in response:
            return True
        elif 'no' in response and 'yes' not in response:
            return False

        # Check first word
        words = response.split()
        if words:
            first_word = words[0]
            if first_word == 'yes':
                return True
            elif first_word == 'no':
                return False

        # Default to None if ambiguous
        return None

    elif property_type == 'scale':
        # Extract number from response
        import re

        # Look for numbers 1-10
        numbers = re.findall(r'\b([1-9]|10)\b', response)

        if numbers:
            try:
                value = int(numbers[0])
                if 1 <= value <= 10:
                    return value
            except ValueError:
                pass

        # Try to find single digit at start
        if response and response[0].isdigit():
            try:
                value = int(response[0])
                if 1 <= value <= 10:
                    return value
            except ValueError:
                pass

        return None

    return None

